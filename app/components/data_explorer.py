
import pandas as pd
import streamlit as st


def _search_frame(
    frame: pd.DataFrame,
    query: str,
    selected_column: str,
) -> pd.DataFrame:
    """Return rows matching a case-insensitive search."""

    if frame.empty or not query.strip():
        return frame.copy()

    query = query.strip()

    if selected_column == "All columns":
        searchable = frame.astype("string").fillna("")
        mask = searchable.apply(
            lambda column: column.str.contains(
                query,
                case=False,
                regex=False,
                na=False,
            )
        ).any(axis=1)

    else:
        if selected_column not in frame.columns:
            return frame.copy()

        mask = (
            frame[selected_column]
            .astype("string")
            .str.contains(
                query,
                case=False,
                regex=False,
                na=False,
            )
        )

    return frame.loc[mask].copy()


def _render_dataset(
    frame: pd.DataFrame,
    title: str,
    key: str,
    description: str,
) -> None:
    """Render a searchable table and CSV download."""

    st.markdown(f"### {title}")
    st.caption(description)

    if frame is None or frame.empty:
        st.info(f"No records are available for {title.lower()}.")
        return

    search_col, column_col = st.columns([2, 1])

    columns = ["All columns"] + frame.columns.tolist()

    with search_col:
        query = st.text_input(
            "Search records",
            placeholder="Enter a value to search...",
            key=f"{key}_search",
        )

    with column_col:
        selected_column = st.selectbox(
            "Search in",
            columns,
            key=f"{key}_column",
        )

    filtered = _search_frame(
        frame,
        query,
        selected_column,
    )

    st.caption(
        f"Showing {len(filtered):,} of {len(frame):,} records"
    )

    st.dataframe(
        filtered,
        use_container_width=True,
        height=440,
        hide_index=True,
    )

    csv_data = filtered.to_csv(index=False).encode("utf-8")

    st.download_button(
        label=f"Download {title} CSV",
        data=csv_data,
        file_name=f"{key}_export.csv",
        mime="text/csv",
        key=f"{key}_download",
        use_container_width=False,
        disabled=filtered.empty,
    )


def render_data_explorer(
    viirs: pd.DataFrame,
    modis: pd.DataFrame,
    matched_pairs: pd.DataFrame,
) -> None:
    """Render searchable source datasets and matching output."""

    st.markdown("## Data Explorer")
    st.caption(
        "SEARCHABLE OBSERVATIONS  /  SOURCE DATA  /  CSV EXPORT"
    )

    st.markdown(
        "Inspect the loaded datasets, search their records, "
        "and export the currently displayed results."
    )

    viirs_tab, modis_tab, pairs_tab = st.tabs(
        [
            "VIIRS observations",
            "MODIS observations",
            "Matched pairs",
        ]
    )

    with viirs_tab:
        _render_dataset(
            viirs,
            "VIIRS observations",
            "viirs",
            "Filtered VIIRS observations, including the two "
            "candidate matching flags.",
        )

    with modis_tab:
        _render_dataset(
            modis,
            "MODIS observations",
            "modis",
            "Filtered MODIS Aqua observations.",
        )

    with pairs_tab:
        _render_dataset(
            matched_pairs,
            "MODIS–VIIRS matched pairs",
            "matched_pairs",
            "Complete matched-pairs output from the scientific "
            "pipeline. This table is not changed by the dashboard "
            "filters; use search to inspect specific records.",
        )

    st.divider()

    st.markdown("### Dataset notes")

    st.markdown(
        """
        - **VIIRS observations:** Suomi-NPP VIIRS detections with
          candidate matching flags.
        - **MODIS observations:** Aqua MODIS detections.
        - **Matched pairs:** Candidate associations generated by
          the matching pipeline using the configured baseline.
        - CSV exports contain the records currently shown after
          applying the table search.
        """
    )

    st.caption(
        "Candidate associations are algorithmic matches, "
        "not verified ground-truth fire detections."
    )
